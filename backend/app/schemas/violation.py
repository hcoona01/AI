from pydantic import BaseModel, ConfigDict, Field

from app.schemas.common import ViolationSeverity


class Violation(BaseModel):
    model_config = ConfigDict(extra="forbid", str_strip_whitespace=True)

    rule_id: str = Field(
        ...,
        min_length=2,
        description="Associated rule_id (e.g., HC-02_TIME_CONFLICT, SC-02_LOAD_FAIRNESS)",
    )
    severity: ViolationSeverity = Field(
        ..., description="Severity level of the violation (error, warning, or info)"
    )
    entity_ids: list[str] = Field(
        default_factory=list,
        description="IDs of related entities involved in the violation (section_id, faculty_id, resource_id)",
    )
    explanation: str = Field(
        ...,
        min_length=1,
        description="Human-readable explanation of why the rule was violated",
    )
    suggested_repairs: list[str] = Field(
        default_factory=list,
        description="Actionable remediation suggestions generated by the repair engine",
    )
